"""Which Actenon dependency artifacts an acceptance run really imports (identity v2).

Identity v1 read each dependency's ``direct_url.json`` and so needed a VCS install. It could not
identify the registry artifacts a release installs, and it recorded the installed commit without
comparing it with the candidate's lock.

v2 binds what is installed to what the candidate's ``uv.lock`` pins, and refuses anything else:

* A git-locked dependency must be installed from exactly the locked commit (``vcs_info``).
* A registry-locked dependency must be that version, installed from a registry rather than from
  git, and its installed files must be exactly the files of one wheel the lock pins.
  - Every installed file is hashed and must match its ``RECORD`` entry.
  - The set of (path, sha256) pairs must equal the wheel's own contents.
  - So a substituted build, an edited file, a rewritten ``RECORD`` or another version is refused.

Wheel bytes come from a content-addressed store and are used only if they hash to the locked
digest. The store is ``AIRLOCK_ACCEPTANCE_ARTIFACTS``, or by default
``~/.cache/actenon-airlock/acceptance-artifacts``. A wheel missing from it is fetched from its
locked URL, and only from PyPI.

Only the standard library is used. Nothing here decides a pass: the acceptance criteria are
unchanged, and this only states, truthfully, which artifacts were under test.
"""

from __future__ import annotations

import base64
import hashlib
import importlib.metadata
import io
import json
import os
import re
import tomllib
import urllib.request
import zipfile
from collections.abc import Callable
from pathlib import Path
from typing import Any

SCHEMA = "actenon-airlock/acceptance-dependency-identity/v2"
NAMES = ("actenon-protocol", "actenon-kernel", "actenon-permit", "actenon-scan")
PYPI_FILES = "https://files.pythonhosted.org/"
# Files an installer writes into .dist-info; they are not part of the artifact.
INSTALLER_FILES = {"INSTALLER", "REQUESTED", "RECORD", "direct_url.json"}
MAX_WHEEL_BYTES = 64 * 1024 * 1024


class IdentityError(Exception):
    """The installed dependencies are not the artifacts the candidate locks."""


def _canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def locked(lock: bytes) -> dict[str, dict[str, Any]]:
    """What ``uv.lock`` pins for each Actenon dependency."""
    try:
        data = tomllib.loads(lock.decode("utf-8"))
    except (UnicodeDecodeError, tomllib.TOMLDecodeError) as exc:
        raise IdentityError(f"uv.lock is unreadable: {exc}") from exc
    pins: dict[str, dict[str, Any]] = {}
    for pkg in data.get("package", []):
        name = _canonical(str(pkg.get("name", "")))
        if name not in NAMES:
            continue
        source = pkg.get("source") or {}
        if "git" in source:
            rev = source["git"].rpartition("#")[2]
            if not re.fullmatch(r"[0-9a-f]{40}", rev):
                raise IdentityError(f"{name} is locked to git without a full commit")
            pins[name] = {"source": "git", "commit": rev}
        elif "registry" in source:
            wheels = {
                str(w.get("hash", "")).removeprefix("sha256:"): str(w.get("url", ""))
                for w in pkg.get("wheels", [])
            }
            if not wheels or not all(re.fullmatch(r"[0-9a-f]{64}", d) for d in wheels):
                raise IdentityError(f"{name} is locked without sha256-pinned wheels")
            pins[name] = {"source": "registry", "version": pkg.get("version"), "wheels": wheels}
        else:
            raise IdentityError(f"{name} is locked from an unsupported source {source}")
    return pins


def _digest(rows: list[tuple[str, str]]) -> str:
    h = hashlib.sha256()
    for path, sha in sorted(rows):
        h.update(f"{path}\0{sha}\n".encode())
    return h.hexdigest()


def _is_installer_file(path: str) -> bool:
    top, _, rest = path.partition("/")
    return top.endswith(".dist-info") and rest in INSTALLER_FILES


def installed_payload(dist: importlib.metadata.Distribution) -> str:
    """The digest of every file this distribution installed, each checked against RECORD."""
    rows = []
    for entry in dist.files or []:
        path = entry.as_posix()
        if path.startswith("../") or "__pycache__/" in path or path.endswith(".pyc"):
            continue  # console scripts and bytecode are generated by the installer
        if _is_installer_file(path):
            continue
        actual = hashlib.sha256(Path(dist.locate_file(entry)).read_bytes()).hexdigest()
        recorded = entry.hash
        expected = (
            base64.urlsafe_b64encode(bytes.fromhex(actual)).rstrip(b"=").decode()
            if recorded is not None and recorded.mode == "sha256"
            else None
        )
        if expected is None or recorded.value != expected:
            raise IdentityError(f"installed {path} does not match its RECORD entry")
        rows.append((path, actual))
    if not rows:
        raise IdentityError(f"{dist.metadata['Name']} has no recorded installed files")
    return _digest(rows)


def wheel_payload(blob: bytes) -> str:
    """The same digest computed from a wheel's own bytes (its RECORD is not trusted)."""
    try:
        archive = zipfile.ZipFile(io.BytesIO(blob))
    except zipfile.BadZipFile as exc:
        raise IdentityError(f"not a wheel: {exc}") from exc
    rows = []
    for name in archive.namelist():
        if name.endswith("/") or _is_installer_file(name):
            continue
        if name.split("/", 1)[0].endswith(".data"):
            raise IdentityError("wheels with a .data directory are not supported")
        rows.append((name, hashlib.sha256(archive.read(name)).hexdigest()))
    return _digest(rows)


def default_store() -> Path:
    configured = os.environ.get("AIRLOCK_ACCEPTANCE_ARTIFACTS")
    if configured:
        return Path(configured)
    return Path.home() / ".cache" / "actenon-airlock" / "acceptance-artifacts"


def wheel_bytes(digest: str, url: str, store: Path) -> bytes:
    """The locked wheel's bytes, from the store if any file there hashes to ``digest``."""
    if store.is_dir():
        for candidate in sorted(store.iterdir()):
            if candidate.is_file() and candidate.stat().st_size <= MAX_WHEEL_BYTES:
                data = candidate.read_bytes()
                if hashlib.sha256(data).hexdigest() == digest:
                    return data
    if not url.startswith(PYPI_FILES):
        raise IdentityError(
            f"locked wheel {digest[:12]} is not in {store} and its URL is not on PyPI: {url}"
        )
    with urllib.request.urlopen(url, timeout=60) as resp:  # noqa: S310 - PyPI only
        data = resp.read(MAX_WHEEL_BYTES + 1)
    if hashlib.sha256(data).hexdigest() != digest:
        raise IdentityError(f"{url} did not serve the locked bytes {digest[:12]}")
    store.mkdir(parents=True, exist_ok=True)
    (store / digest).write_bytes(data)
    return data


def identify(
    lock_path: Path,
    *,
    store: Path | None = None,
    distribution: Callable[
        [str], importlib.metadata.Distribution
    ] = importlib.metadata.distribution,
) -> dict[str, dict[str, Any]]:
    """Identify each Actenon dependency, refusing any that is not the locked artifact."""
    pins = locked(Path(lock_path).read_bytes())
    store = store if store is not None else default_store()
    identity: dict[str, dict[str, Any]] = {}
    for name in NAMES:
        pin = pins.get(name)
        if pin is None:
            raise IdentityError(f"{name} is not locked in {lock_path}")
        try:
            dist = distribution(name)
        except importlib.metadata.PackageNotFoundError as exc:
            raise IdentityError(f"{name} is not installed") from exc
        direct = json.loads(dist.read_text("direct_url.json") or "null") or {}
        installed_commit = (direct.get("vcs_info") or {}).get("commit_id")
        if pin["source"] == "git":
            if installed_commit != pin["commit"]:
                origin = installed_commit or "a package index"
                raise IdentityError(
                    f"{name} is locked at {pin['commit'][:12]} but installed from {origin}"
                )
            identity[name] = {"install": "vcs", "commit": installed_commit}
            continue
        if installed_commit or "dir_info" in direct:
            raise IdentityError(f"{name} is locked from a registry but installed from source")
        if dist.version != pin["version"]:
            raise IdentityError(
                f"{name} {dist.version} is installed but {pin['version']} is locked"
            )
        payload = installed_payload(dist)
        matches = [
            digest
            for digest, url in sorted(pin["wheels"].items())
            if wheel_payload(wheel_bytes(digest, url, store)) == payload
        ]
        if len(matches) != 1:
            raise IdentityError(f"installed {name} files are not exactly one locked wheel")
        identity[name] = {
            "install": "registry",
            "version": dist.version,
            "artifact_sha256": matches[0],
            "payload_sha256": payload,
        }
    return identity
